import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";

import { validateThemeV2 } from "../themes/theme-v2.mjs";

const root = path.resolve(import.meta.dirname, "..");
const catalogDirectory = path.join(root, "themes", "catalog");
const publicationCatalog = JSON.parse(await fs.readFile(
  path.join(root, "themes", "platform-publication-catalog.json"),
  "utf8",
));
if (publicationCatalog.schemaVersion !== 2 || !Array.isArray(publicationCatalog.items)) {
  throw new Error("themes/platform-publication-catalog.json is invalid");
}
const publishedItems = publicationCatalog.items;
const ids = publishedItems.map((item) => item.id);
if (new Set(ids).size !== ids.length) throw new Error("Platform publication catalog contains duplicate ids");

const items = [];
for (const [index, id] of ids.entries()) {
  const published = publishedItems[index];
  const assetFile = path.basename(published.assetUrl ?? "");
  if (!/^\d{2,3}-[a-z0-9-]+\.webp$/.test(assetFile) || !published.assetUrl.endsWith(`/${assetFile}`)) {
    throw new Error(`${id} has an invalid platform asset URL`);
  }
  const directory = path.join(root, "themes", "catalog", id);
  const themeBytes = await fs.readFile(path.join(directory, "theme.json"));
  const theme = validateThemeV2(JSON.parse(themeBytes.toString("utf8")));
  if (theme.id !== id) throw new Error(`${id} has a mismatched theme id`);
  const poster = await fs.readFile(path.join(directory, theme.media.poster));
  const preview = await fs.readFile(path.join(directory, "preview.webp"));
  const video = theme.media.video ? await fs.readFile(path.join(directory, theme.media.video)) : null;
  items.push({
    id,
    name: theme.name,
    version: 2,
    family: theme.family,
    appearance: theme.appearance,
    mediaKind: video ? "video" : "static",
    riskStatus: theme.risk.status,
    assetFile,
    platforms: ["macos", "windows"],
    hashes: {
      theme: createHash("sha256").update(themeBytes).digest("hex"),
      poster: createHash("sha256").update(poster).digest("hex"),
      preview: createHash("sha256").update(preview).digest("hex"),
      video: video ? createHash("sha256").update(video).digest("hex") : null,
    },
    theme,
  });
}

const catalog = {
  schemaVersion: 2,
  assetOrigin: "https://nexotoken.net",
  items,
};
const output = `${JSON.stringify(catalog, null, 2)}\n`;
const embeddedOutput = `import Foundation\n\n// Generated by tools/build-theme-catalog.mjs. Do not edit.\nenum EmbeddedNexoSkinCatalog {\n  static let data = Data(base64Encoded: "${Buffer.from(output, "utf8").toString("base64")}")\n}\n`;
const targets = [
  path.join(root, "themes", "catalog.json"),
  path.join(root, "macos", "menubar-app", "Sources", "DreamSkinCore", "Resources", "nexo-skin-catalog.json"),
  path.join(root, "windows", "assets", "nexo-skin-catalog.json"),
];
for (const target of targets) {
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, output, "utf8");
}
await fs.writeFile(
  path.join(root, "macos", "menubar-app", "Sources", "DreamSkinCore", "EmbeddedNexoSkinCatalog.swift"),
  embeddedOutput,
  "utf8",
);
process.stdout.write(`${JSON.stringify({ themes: items.length })}\n`);
